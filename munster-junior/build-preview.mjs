import {readFile,writeFile} from 'node:fs/promises';
import {DIVISIONS} from './divisions.mjs';
const root=new URL('.',import.meta.url);
const read=p=>readFile(new URL(p,root),'utf8');
let html=await read('page-template.html');
const css=await read('public/style.css');
const js=await read('public/app.js');
const pwa=await read('public/pwa.js');
const snapshots=Object.fromEntries(await Promise.all(Object.entries(DIVISIONS).map(async([id,config])=>[id,JSON.parse(await read(config.snapshot))])));
const logos={...JSON.parse(await read('club-logos.json')),...JSON.parse(await read('club-logos-south.json'))};
const safe=s=>s.replace(/<\/script/gi,'<\\/script');
html=html.replace('<link rel="stylesheet" href="/style.css">','<style>'+css+'</style>');
html=html.replace('<script src="/app.js" defer></script>','');
html=html.replace('<script src="/pwa.js" defer></script>','');
html=html.replace('</body>','<script>window.MJ_DIVISIONS='+safe(JSON.stringify(DIVISIONS))+';window.MJ_SNAPSHOTS='+safe(JSON.stringify(snapshots))+';window.MJ_LOGOS='+safe(JSON.stringify(logos))+';</script><script>'+safe(js)+'</script><script>'+safe(pwa)+'</script></body>');
await writeFile(new URL('public/index.html',root),html);
console.log('Built self-contained preview for '+Object.keys(snapshots).length+' leagues.');
